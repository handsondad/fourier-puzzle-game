import { PHOTO_SIZE, type PhotoItem } from "../lib/photoWaves.ts";

const TONE: Record<string, number> = { ".": 0, ":": 0.3, "o": 0.65, "#": 1 };

function art(rows: readonly string[]): number[] {
  const out: number[] = [];
  for (const row of rows) {
    for (let i = 0; i < PHOTO_SIZE; i++) out.push(TONE[row[i] ?? "."] ?? 0);
  }
  return out;
}

